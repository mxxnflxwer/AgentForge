import logging
import time
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.services.evaluation.cost import CostBreakdown, calculate_cost
from app.services.evaluation.groundedness import GroundednessResult, calculate_groundedness
from app.services.evaluation.hallucination import HallucinationResult, calculate_hallucination_rate
from app.services.evaluation.metrics import calculate_accuracy, extract_token_usage

logger = logging.getLogger("agentforge.services.evaluation.evaluator")


class EvaluationInput(BaseModel):
    """Input payload for evaluating an LLM response against retrieved RAG context."""
    question: str = Field(..., description="The user or benchmark question")
    generated_answer: str = Field(..., description="The answer generated by the LLM")
    retrieved_context: str = Field(..., description="Retrieved context chunks used for grounding")
    expected_answer: Optional[str] = Field(None, description="Optional reference/ground-truth answer for accuracy calculation")
    model_name: str = Field(..., description="Name or identifier of the evaluated model")
    input_tokens: Optional[int] = Field(None, description="Explicit input token count if known")
    output_tokens: Optional[int] = Field(None, description="Explicit output token count if known")
    latency_ms: Optional[float] = Field(None, description="LLM round-trip latency in milliseconds")
    execution_time_ms: Optional[float] = Field(None, description="Total pipeline execution time in milliseconds")
    raw_usage: Optional[Dict[str, Any]] = Field(None, description="Raw provider usage metadata")


class EvaluationResult(BaseModel):
    """Unified standardized evaluation result across all AgentEvo metrics."""
    model: str = Field(..., description="Model identifier")
    accuracy: Optional[float] = Field(None, description="Factual accuracy score [0.0 - 1.0] if reference answer was provided")
    groundedness: float = Field(..., description="Groundedness score: supported_claims / total_claims [0.0 - 1.0]")
    hallucination_rate: float = Field(..., description="Hallucination rate: unsupported_claims / total_claims [0.0 - 1.0]")
    supported_claims: int = Field(..., description="Number of supported factual assertions")
    unsupported_claims: List[str] = Field(default_factory=list, description="List of unsupported or hallucinated claim statements")
    total_claims: int = Field(..., description="Total evaluated factual claims")
    input_tokens: int = Field(..., description="Input token count")
    output_tokens: int = Field(..., description="Output token count")
    total_tokens: int = Field(..., description="Total tokens: input + output")
    latency_ms: float = Field(..., description="LLM generation latency in ms")
    execution_time_ms: float = Field(..., description="End-to-end execution time in ms")
    input_cost: float = Field(..., description="Input token cost in USD")
    output_cost: float = Field(..., description="Output token cost in USD")
    total_cost: float = Field(..., description="Total cost in USD")
    details: Dict[str, Any] = Field(default_factory=dict, description="Fine-grained claim and evaluation diagnostics")


class EvaluationEngine:
    """
    AgentEvo Core Evaluation Engine.
    Executes comprehensive multi-metric evaluation across accuracy, groundedness,
    hallucination rate, token usage, latency, execution time, and cost.
    """

    def evaluate(self, input_data: EvaluationInput) -> EvaluationResult:
        """
        Evaluate a single LLM execution input and calculate all standardized metrics.
        """
        start_eval_time = time.perf_counter()

        # 1. Groundedness Evaluation
        groundedness_res: GroundednessResult = calculate_groundedness(
            generated_answer=input_data.generated_answer,
            retrieved_context=input_data.retrieved_context,
        )

        # 2. Hallucination Rate Evaluation (reuses claim breakdown for efficiency)
        hallucination_res: HallucinationResult = calculate_hallucination_rate(
            generated_answer=input_data.generated_answer,
            retrieved_context=input_data.retrieved_context,
            groundedness_result=groundedness_res,
        )

        # 3. Accuracy Evaluation (if expected answer is present)
        accuracy_score = calculate_accuracy(
            generated_answer=input_data.generated_answer,
            expected_answer=input_data.expected_answer,
        )

        # 4. Token Usage Calculation
        if input_data.input_tokens is not None and input_data.output_tokens is not None:
            input_toks = max(0, input_data.input_tokens)
            output_toks = max(0, input_data.output_tokens)
            total_toks = input_toks + output_toks
        else:
            token_usage = extract_token_usage(
                raw_usage=input_data.raw_usage,
                generated_answer=input_data.generated_answer,
                retrieved_context=input_data.retrieved_context,
                query=input_data.question,
            )
            input_toks = token_usage.input_tokens
            output_toks = token_usage.output_tokens
            total_toks = token_usage.total_tokens

        # 5. Cost Computation
        cost_breakdown: CostBreakdown = calculate_cost(
            model_name=input_data.model_name,
            input_tokens=input_toks,
            output_tokens=output_toks,
        )

        # 6. Timing & Latency
        latency = input_data.latency_ms if input_data.latency_ms is not None else 0.0
        eval_duration_ms = round((time.perf_counter() - start_eval_time) * 1000, 2)
        exec_time = (
            input_data.execution_time_ms
            if input_data.execution_time_ms is not None
            else round(latency + eval_duration_ms, 2)
        )

        # 7. Diagnostic Details
        details: Dict[str, Any] = {
            "evaluation_duration_ms": eval_duration_ms,
            "claim_breakdown": [c.model_dump() for c in groundedness_res.claim_details],
            "pricing_applied": input_data.model_name,
        }

        return EvaluationResult(
            model=input_data.model_name,
            accuracy=accuracy_score,
            groundedness=groundedness_res.groundedness,
            hallucination_rate=hallucination_res.hallucination_rate,
            supported_claims=groundedness_res.supported_claims,
            unsupported_claims=hallucination_res.unsupported_claims,
            total_claims=groundedness_res.total_claims,
            input_tokens=input_toks,
            output_tokens=output_toks,
            total_tokens=total_toks,
            latency_ms=round(latency, 2),
            execution_time_ms=round(exec_time, 2),
            input_cost=cost_breakdown.input_cost,
            output_cost=cost_breakdown.output_cost,
            total_cost=cost_breakdown.total_cost,
            details=details,
        )

    def evaluate_batch(self, inputs: List[EvaluationInput]) -> List[EvaluationResult]:
        """Evaluate multiple LLM execution inputs in sequence."""
        return [self.evaluate(inp) for inp in inputs]

    def evaluate_workflow(self, workflow_data: Dict[str, Any]) -> EvaluationResult:
        """
        Evaluate a complete workflow execution dictionary.
        Prepared for the Phase 7 AgentEvo Autonomous Optimizer.

        Expected workflow_data structure:
        {
            "question": "...",
            "generated_answer": "...",
            "retrieved_context": "...",
            "expected_answer": "...", # optional
            "model_name": "...",
            "latency_ms": 120.0,
            "execution_time_ms": 450.0,
            "raw_usage": {...}
        }
        """
        eval_input = EvaluationInput(
            question=workflow_data.get("question", ""),
            generated_answer=workflow_data.get("generated_answer", ""),
            retrieved_context=workflow_data.get("retrieved_context", ""),
            expected_answer=workflow_data.get("expected_answer"),
            model_name=workflow_data.get("model_name", "gemini-3.5-flash-lite"),
            input_tokens=workflow_data.get("input_tokens"),
            output_tokens=workflow_data.get("output_tokens"),
            latency_ms=workflow_data.get("latency_ms"),
            execution_time_ms=workflow_data.get("execution_time_ms"),
            raw_usage=workflow_data.get("raw_usage"),
        )
        return self.evaluate(eval_input)


# Singleton instance
_evaluation_engine_instance: Optional[EvaluationEngine] = None


def get_evaluation_engine() -> EvaluationEngine:
    global _evaluation_engine_instance
    if _evaluation_engine_instance is None:
        _evaluation_engine_instance = EvaluationEngine()
    return _evaluation_engine_instance


def evaluate_workflow(workflow_data: Dict[str, Any]) -> EvaluationResult:
    """Convenience top-level function for AgentEvo workflow evaluation."""
    return get_evaluation_engine().evaluate_workflow(workflow_data)
